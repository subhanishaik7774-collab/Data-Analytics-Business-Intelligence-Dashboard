// Initialize PostgreSQL Pool if URI is set
if (process.env.DATABASE_URL) {
  try {
    pool = new Pool({
      connectionString: process.env.DATABASE_URL,
      ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : false
    });

    // Test the database connection
    pool.query('SELECT NOW()', (err, res) => {
      if (err) {
        console.warn('⚠️  PostgreSQL connection failed. Falling back to In-Memory Demo Mode.');
        console.warn('Reason:', err.message);
        isDemoMode = true;
      } else {
        console.log('⚡ Connected to PostgreSQL successfully! Database queries are active.');
      }
    });
  } catch (err) {
    console.warn('⚠️  Failed to construct Pool. Falling back to In-Memory Demo Mode.');
    isDemoMode = true;
  }
} else {
  console.log('ℹ️  No DATABASE_URL environment variable found. Starting in In-Memory Demo Mode.');
  isDemoMode = true;
}

